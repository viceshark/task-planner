package ru.planner.domain;

/** Вид события, занимающего сотрудника вместо задач. */
public enum AbsenceType {
    /** Простой — сотрудник без задач (может быть часть дня). */
    DOWNTIME,
    /** Аренда — сотрудника забрали в другую команду на период. */
    RENTAL,
    /** Отпуск. */
    VACATION
}
